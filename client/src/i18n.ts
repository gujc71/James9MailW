const dict: Record<Locale, Record<MessageKey, string>> = { ko, en };

let current: Locale = readStored();
const listeners = new Set<() => void>();

function readStored(): Locale {
  try {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved === 'ko' || saved === 'en') return saved;
  } catch {
    // 비공개 창 등에서 접근 불가
  }
  return DEFAULT_LOCALE;
}

export function getLocale(): Locale {
  return current;
}

/** 언어 전환. 로그인 화면과 로그인 직후(Me.locale)가 부른다 */
export function setLocale(next: Locale): void {
  if (next === current) return;
  current = next;
  try {
    localStorage.setItem(STORE_KEY, next);
  } catch {
    // 저장 실패는 무시
  }
  if (typeof document !== 'undefined') document.documentElement.lang = next;
  for (const listener of listeners) listener();
}

/** 문구 한 줄. params 로 {name} 자리를 채운다 */
export function t(key: MessageKey, params?: Record<string, string | number>): string {
  const template = dict[current][key] ?? ko[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}

function subscribe(onChange: () => void): () => void {
  listeners.add(onChange);
  return () => {
    listeners.delete(onChange);
  };
}

/** 언어가 바뀌면 다시 그린다. 컴포넌트에서는 const t = useT() 로 쓴다 */
export function useT(): typeof t {
  useSyncExternalStore(subscribe, getLocale, () => DEFAULT_LOCALE);
  return t;
}

export function useLocale(): Locale {
  return useSyncExternalStore(subscribe, getLocale, () => DEFAULT_LOCALE);
}

